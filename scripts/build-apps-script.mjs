import {readFile,mkdir,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const files=['server/google-apps-script.gs','server/collaboration.gs'];
const source=(await Promise.all(files.map(file=>readFile(new URL(file,root),'utf8')))).join('\n\n');
await mkdir(new URL('output/apps-script/',root),{recursive:true});
await writeFile(new URL('output/apps-script/Code.gs',root),'// Generated by node scripts/build-apps-script.mjs. Edit source files under server/.\n'+source);
console.log('Ready to paste into the existing Apps Script project: output/apps-script/Code.gs');
